#!/usr/bin/env python3
"""Generate the smoke-test inventory of ported sources."""
import os
import re

SITES = "/data/data/com.termux/files/home/AIO-Hentai/AIO-Hentai/src/main/kotlin/com/aiohentai/cs/sites"
OUT = "/data/data/com.termux/files/home/AIO-Hentai/scripts/SmokeSites.kt"

entries = []
for site in sorted(os.listdir(SITES)):
    d = os.path.join(SITES, site)
    if not os.path.isdir(d):
        continue
    for name in sorted(os.listdir(d)):
        if name.endswith("Provider.kt"):
            continue
        text = open(os.path.join(d, name), encoding="utf-8").read()
        m = re.search(r"^class (\w+) : AnimeHttpSource\(\)", text, re.M)
        if m:
            entries.append((site, m.group(1)))

lines = [
    "package com.aiohentai.cs.smoke",
    "",
    "import com.aiohentai.cs.compat.AnimeHttpSource",
]
for site, cls in entries:
    lines.append(f"import com.aiohentai.cs.sites.{site}.{cls}")

lines += [
    "",
    "/** Generated by scripts/gen_smoke.py */",
    "fun smokeSites(): List<Pair<String, () -> AnimeHttpSource>> = listOf(",
]
for site, cls in entries:
    lines.append(f'    "{cls}" to {{ {cls}() }},')
lines.append(")")
lines.append("")

with open(OUT, "w", encoding="utf-8") as fh:
    fh.write("\n".join(lines))
print(f"{len(entries)} sources")
